package field_types

import (
	"sort"
)

// +k8s:deepcopy-gen=true
type ServingPortsField struct {
	Rules     *MapRules                           `json:"rules,omitempty"`
	ItemRules *ServingPortItemRules               `json:"itemRules,omitempty"`
	Value     *map[string]ServingPortItemAndRules `json:"items,omitempty"`
}

// +k8s:deepcopy-gen=true
type ServingPortItemAndRules struct {
	Rules   *MapItemRules         `json:"rules,omitempty"`
	Value   *ServingPortItemValue `json:"value,omitempty"`
	Deleted *bool                 `json:"deleted,omitempty"`
}

// +k8s:deepcopy-gen=true
type ServingPortItemRules struct {
	Port              *IntRules    `json:"port,omitempty"`
	Protocol          *StringRules `json:"protocol,omitempty"`
	ExposeExternally  *BoolRules   `json:"exposeExternally,omitempty"`
	ExposedUrl        *StringRules `json:"exposedUrl,omitempty"`
	AuthorizationType *StringRules `json:"authorizationType,omitempty"`
	AuthorizedUsers   *StringRules `json:"authorizedUsers,omitempty"`
	AuthorizedGroups  *StringRules `json:"authorizedGroups,omitempty"`
}

// +k8s:deepcopy-gen=true
type ServingPortItemValue struct {
	// The ServingPort number to expose.
	// +optional
	Port *int `json:"port,omitempty"`
	// The protocol to use for the serving ServingPort. Possible values are: http (default).
	Protocol *string `json:"protocol,omitempty"`
	// Whether to expose the ServingPort via an external URL or a cluster-local one. Defaults to true.
	ExposeExternally *bool `json:"exposeExternally,omitempty"`
	// The custom URL to use for the ServingPort. If empty (default), an autogenerated URL will be used.
	// +kubebuilder:validation:Format:=uri
	ExposedUrl *string `json:"exposedUrl,omitempty"`
	// The authorization type. Possible values are: public (default), authenticatedUsers, authorizedUsers, authorizedGroups
	AuthorizationType *string `json:"authorizationType,omitempty"`
	// The list of users that are allowed to access the serving ServingPort (seperated by comma).
	// Should be provided if and only if the authorization type is set to authorizedUsers.
	AuthorizedUsers *string `json:"authorizedUsers,omitempty"`
	// The list of groups that are allowed to access the serving ServingPort (seperated by comma).
	// Should be provided if and only if the authorization type is set to authorizedGroups.
	AuthorizedGroups *string `json:"authorizedGroups,omitempty"`
}

func (s *ServingPortsField) Deref() map[string]ServingPortItemAndRules {
	if s != nil && s.Value != nil {
		return *s.Value
	} else {
		return map[string]ServingPortItemAndRules{}
	}
}

func NewServingPortsField(ServingPortsMap map[string]ServingPortItemAndRules) *ServingPortsField {
	if len(ServingPortsMap) == 0 {
		return nil
	}
	return &ServingPortsField{
		Value: &ServingPortsMap,
	}
}

func SortedServingPortsMapKeys(unsorted map[string]ServingPortItemAndRules) []string {
	result := make([]string, 0, len(unsorted))
	for k := range unsorted {
		result = append(result, k)
	}
	sort.Strings(result)
	return result
}
