package networking

import (
	"encoding/json"
	"fmt"
	"regexp"
	"sort"

	workloadconfig "github.com/dsx-ai-factory/run-ai/runai-cluster/cluster/workload-common/config"
	openshiftv1 "github.com/openshift/api/route/v1"
	corev1 "k8s.io/api/core/v1"
	networkingv1 "k8s.io/api/networking/v1"
	"k8s.io/utils/ptr"
	"sigs.k8s.io/controller-runtime/pkg/client"
	gatewayv1 "sigs.k8s.io/gateway-api/apis/v1"
)

const ingressClassAnnotation = "kubernetes.io/ingress.class"

// These settings are administrator-owned, not derived from a submission profile
// or from the object being validated. Exact defaults are explicitly trusted
// infrastructure; they are not evidence that their destinations are workload Pods.
type routingConstraints struct {
	ingressClass       string
	gatewayName        string
	gatewayNamespace   string
	ingressAnnotations map[string]string
}

func configuredRoutingConstraints() routingConstraints {
	return routingConstraints{
		ingressClass:       workloadconfig.IngressClass(),
		gatewayName:        workloadconfig.GatewayName(),
		gatewayNamespace:   workloadconfig.GatewayNamespace(),
		ingressAnnotations: workloadconfig.IngressAnnotations(),
	}
}

// validateExposureExtensions complements backend ownership checks: opaque
// controller instructions must not introduce destinations outside that graph.
// Labels and independently attached administrator policies are not checked here.
func validateExposureExtensions(object client.Object, constraints routingConstraints) error {
	var errs []error
	switch exposure := object.(type) {
	case *networkingv1.Ingress:
		errs = append(errs, validateIngressClass(exposure, constraints.ingressClass))
	case *openshiftv1.Route:
	case *gatewayv1.HTTPRoute:
		errs = append(errs, validateHTTPRouteFilters(exposure), validateGatewayParents(exposure, constraints))
	default:
		return nil // Unsupported kinds are reported by the backend extractor.
	}
	return prioritizeOwnershipErrors(append(errs, validateRoutingAnnotations(object, constraints))...)
}

func validateIngressClass(ingress *networkingv1.Ingress, approved string) error {
	class := ptr.Deref(ingress.Spec.IngressClassName, "")
	legacyClass, hasLegacyClass := ingress.Annotations[ingressClassAnnotation]
	// A configured Run:ai class need not be the Kubernetes default. Require it
	// on live objects as well as rendered input. With no Run:ai setting, only
	// omission (the administrator's Kubernetes default) is accepted.
	if (class != "" && class != approved) || (hasLegacyClass && (legacyClass == "" || legacyClass != approved)) {
		return ownershipViolationf("Ingress %s/%s must use the configured Ingress class", ingress.Namespace, ingress.Name)
	}
	if approved != "" && class == "" && !hasLegacyClass {
		return ownershipViolationf("Ingress %s/%s is missing the configured Ingress class", ingress.Namespace, ingress.Name)
	}
	return nil
}

func validateGatewayParents(route *gatewayv1.HTTPRoute, constraints routingConstraints) error {
	var errs []error
	for i, parent := range route.Spec.ParentRefs {
		group := ptr.Deref(parent.Group, gatewayv1.Group(gatewayv1.GroupName))
		kind := ptr.Deref(parent.Kind, gatewayv1.Kind("Gateway"))
		namespace := string(ptr.Deref(parent.Namespace, gatewayv1.Namespace(route.Namespace)))
		if group != gatewayv1.GroupName || kind != "Gateway" || constraints.gatewayName == "" ||
			string(parent.Name) != constraints.gatewayName || namespace != constraints.gatewayNamespace {
			errs = append(errs, ownershipViolationf(
				"HTTPRoute %s/%s parentRefs[%d] must reference the configured Gateway",
				route.Namespace, route.Name, i,
			))
		}
	}
	return prioritizeOwnershipErrors(errs...)
}

var (
	annotationSize    = regexp.MustCompile(`^[0-9]+[kKmMgG]?$`)
	annotationNumber  = regexp.MustCompile(`^[0-9]+(?:\.[0-9]+)?$`)
	annotationInteger = regexp.MustCompile(`^[0-9]+$`)
	annotationHash    = regexp.MustCompile(`^[a-z0-9]+$`)
	routeTimeout      = regexp.MustCompile(`^[0-9]+(?:us|ms|s|m|h|d)?$`)
	// This is the one HAProxytech rewrite form generated by the NIM composer,
	// not a generic check for executable annotation content.
	haproxyPathRewrite = regexp.MustCompile(`^/[A-Za-z0-9._~/-]*\(/\|\$\)\(\.\*\) /\\2$`)
)

func validateRoutingAnnotations(object client.Object, constraints routingConstraints) error {
	annotations := object.GetAnnotations()
	keys := make([]string, 0, len(annotations))
	for key := range annotations {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	var errs []error
	for _, key := range keys {
		value := annotations[key]
		if allowedRoutingAnnotation(object, key, value, constraints) {
			continue
		}
		// Do not echo values: annotations can contain credentials or large snippets.
		errs = append(errs, ownershipViolationf(
			"%T %s/%s annotation %q has an unsupported key or value",
			object, object.GetNamespace(), object.GetName(), key,
		))
	}
	return prioritizeOwnershipErrors(errs...)
}

func allowedRoutingAnnotation(object client.Object, key, value string, constraints routingConstraints) bool {
	switch resource := object.(type) {
	case *networkingv1.Ingress:
		if key == ingressClassAnnotation {
			return value != "" && value == constraints.ingressClass
		}
		if configured, found := constraints.ingressAnnotations[key]; found && value == configured {
			return true
		}
		switch key {
		case "nginx.ingress.kubernetes.io/proxy-body-size":
			return annotationSize.MatchString(value)
		case "nginx.ingress.kubernetes.io/backend-protocol":
			return value == "GRPC"
		case "nginx.ingress.kubernetes.io/rewrite-target":
			return value == "/$2"
		case "haproxy.ingress.kubernetes.io/backend-protocol":
			return value == "grpc"
		case "haproxy.ingress.kubernetes.io/rewrite-target":
			return value == `/\1`
		case "haproxy.ingress.kubernetes.io/request-set-header":
			return value == "X-Forwarded-Uri %[req.uri]"
		case "haproxy.org/path-rewrite":
			if !haproxyPathRewrite.MatchString(value) {
				return false
			}
			for _, rule := range resource.Spec.Rules {
				if rule.HTTP != nil {
					for _, path := range rule.HTTP.Paths {
						if value == fmt.Sprintf(`%s /\2`, path.Path) {
							return true
						}
					}
				}
			}
		}
	case *openshiftv1.Route:
		if configured, found := constraints.ingressAnnotations[key]; found && value == configured {
			return true
		}
		if key == "haproxy.router.openshift.io/timeout" {
			return routeTimeout.MatchString(value)
		}
		// OpenShift host allocation adds this to Routes with an omitted host.
		if key == "openshift.io/host.generated" {
			return value == "true"
		}
	case *corev1.Service:
		// NIM operator bookkeeping copied to referenced Services. No origin or
		// prefix exemption: user annotations on NIM Services use these same rules.
		switch key {
		case "openshift.io/scc", "openshift.io/required-scc":
			return value == "nonroot" || value == "anyuid" || value == "hostmount-anyuid"
		case "nvidia.com/parent-spec-hash":
			return annotationHash.MatchString(value)
		case "gpu-memory", "gpu-fraction", "gpu-fraction-num-devices":
			return annotationNumber.MatchString(value)
		case "deployment.kubernetes.io/revision":
			return annotationInteger.MatchString(value)
		}
	}
	// kubectl bookkeeping is also present on live objects and carries no routing
	// instruction for the supported controllers. It is not interpreted as defaults.
	return key == "kubectl.kubernetes.io/last-applied-configuration" && (value == "" || json.Valid([]byte(value)))
}
