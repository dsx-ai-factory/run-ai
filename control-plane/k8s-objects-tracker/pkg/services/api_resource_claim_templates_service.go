// ResourceClaimTemplatesApiService implements the ResourceClaimTemplatesAPIServicer
// generated by openapi-generator. ResourceClaimTemplates are tracked in the shared
// `objects` table (ObjectType "ResourceClaimTemplate") and may live in cluster,
// department, or project scope. Unlike the earlier per-scope URL design, scope
// now travels in the body (POST/PUT/Sync) or in the query (DELETE), so a single
// surface per verb replaces the three scope-flavoured endpoints we used before.
type ResourceClaimTemplatesApiService struct{}

// NewResourceClaimTemplatesApiService creates a default api service.
func NewResourceClaimTemplatesApiService() api.ResourceClaimTemplatesAPIServicer {
	return &ResourceClaimTemplatesApiService{}
}

// CreateResourceClaimTemplate upserts a single tracked RCT. The item carries
// its own scope (scopeType + scopeId) in the body; no pruning is performed -
// the caller is only asserting the presence of this one template.
func (s *ResourceClaimTemplatesApiService) CreateResourceClaimTemplate(ctx context.Context, clusterId string, rct api.ResourceClaimTemplate) (api.ImplResponse, error) {
	return s.upsertOne(ctx, clusterId, rct)
}

// UpdateResourceClaimTemplate updates a single tracked RCT. PUT and POST do the
// same work; the two verbs exist for client-side intent clarity, matching the
// StorageClass / DeviceClass per-item CRUD pattern.
func (s *ResourceClaimTemplatesApiService) UpdateResourceClaimTemplate(ctx context.Context, clusterId string, rct api.ResourceClaimTemplate) (api.ImplResponse, error) {
	return s.upsertOne(ctx, clusterId, rct)
}

// DeleteResourceClaimTemplate removes a single tracked RCT. The identity
// (clusterId, scopeType, scopeId, name) comes from the query string so DELETE
// has no body - matching the per-item DELETE shape used by DeviceClass.
func (s *ResourceClaimTemplatesApiService) DeleteResourceClaimTemplate(ctx context.Context, clusterId string, scopeTypeStr string, scopeId string, name string) (api.ImplResponse, error) {
	tenantId, apiErr := common.TenantIdFromContext(ctx)
	if apiErr != nil {
		return NewErrorResponse(apiErr), nil
	}

	if err := common.ValidateScopeType(scopeTypeStr); err != nil {
		return NewErrorResponse(err), nil
	}

	clusterUuid, err := uuid.Parse(clusterId)
	if err != nil {
		return NewErrorResponse(api.NewError(http.StatusBadRequest, "invalid cluster ID format", nil)), nil
	}

	if name == "" {
		return NewErrorResponse(api.NewValidationError("resource claim template name is mandatory")), nil
	}

	filters := &models.ObjectFilters{
		Type:      models.ObjectTypeResourceClaimTemplate,
		TenantId:  tenantId,
		ClusterId: clusterUuid,
		ScopeType: authclient.ScopeType(scopeTypeStr),
		Name:      &name,
	}
	if apiErr := assignScopeId(filters, clusterUuid.String(), scopeId); apiErr != nil {
		return NewErrorResponse(apiErr), nil
	}

	if apiErr := dao.Delete(ctx, filters); apiErr != nil {
		logging.WithCtx(runaictx.LoggerHook(ctx)).Errorf("failed deleting resource claim template %s: %v", name, apiErr)
		return NewErrorResponse(apiErr), nil
	}

	return api.Response(http.StatusNoContent, nil), nil
}

// SyncResourceClaimTemplates performs a full-set replace of every RCT the
// cluster currently observes. The payload is cluster-wide: items may live at
// cluster, department, or project scope within the same request, and anything
// in the cluster whose id is not surfaced by the payload is removed - even if
// it is in a scope the payload did not otherwise mention. This matches the
// agent's model: a sync call declares the entire inventory the cluster still
// has, so a missing row means "it is gone".
func (s *ResourceClaimTemplatesApiService) SyncResourceClaimTemplates(ctx context.Context, clusterId string, rcts api.ResourceClaimTemplates) (api.ImplResponse, error) {
	tenantId, apiErr := common.TenantIdFromContext(ctx)
	if apiErr != nil {
		return NewErrorResponse(apiErr), nil
	}

	clusterUuid, err := uuid.Parse(clusterId)
	if err != nil {
		return NewErrorResponse(api.NewError(http.StatusBadRequest, "invalid cluster ID format", nil)), nil
	}

	keptKeys := make([][]interface{}, 0, len(rcts.Items))
	for i := range rcts.Items {
		rct := rcts.Items[i]
		if rct.Name == "" {
			return NewErrorResponse(api.NewValidationError("resource claim template name is mandatory")), nil
		}

		obj, apiErr := resourceClaimTemplateApiToDb(tenantId, clusterUuid, &rct)
		if apiErr != nil {
			return NewErrorResponse(apiErr), nil
		}

		if _, apiErr := dao.UpsertObject(ctx, obj); apiErr != nil {
			logging.WithCtx(runaictx.LoggerHook(ctx)).Errorf("failed upserting resource claim template %s: %v", rct.Name, apiErr)
			return NewErrorResponse(apiErr), nil
		}

		if _, apiErr := HandleResourceIssues(ctx, tenantId, clusterId,
			string(rct.ScopeType), rct.ScopeId, obj.ID.String(),
			rct.Issues, string(api.CLUSTERRESOURCETYPE_RESOURCE_CLAIM_TEMPLATE)); apiErr != nil {
			logging.WithCtx(runaictx.LoggerHook(ctx)).Errorf("failed updating resource issues for %s: %v", rct.Name, apiErr)
			return NewErrorResponse(apiErr), nil
		}

		keptKeys = append(keptKeys,
			[]interface{}{string(obj.ScopeType), obj.DepartmentId, obj.ProjectId, rct.Name})
	}

	// Cluster-wide prune by composite natural key (scope_type, department_id,
	// project_id, name). This matches what the cluster-sync agent actually
	// sends (it has no notion of our row ids) and is identity-safe when the
	// same template name appears at multiple scopes.
	clusterFilter := &models.ObjectFilters{
		Type:      models.ObjectTypeResourceClaimTemplate,
		TenantId:  tenantId,
		ClusterId: clusterUuid,
	}
	if apiErr := dao.DeleteObjectsNotInScopedKeys(ctx, clusterFilter, keptKeys); apiErr != nil {
		logging.WithCtx(runaictx.LoggerHook(ctx)).Errorf("failed pruning stale resource claim templates: %v", apiErr)
		return NewErrorResponse(apiErr), nil
	}

	return api.Response(http.StatusOK, rcts), nil
}

// ListResourceClaimTemplates lists tracked RCTs filtered by scope / cluster /
// name / origin. Cross-scope expansion (ancestors / descendants) is not wired
// in - the objects table does not go through BuildScopeQuery (which is
// PVC-specific) and no caller needs it today.
func (s *ResourceClaimTemplatesApiService) ListResourceClaimTemplates(ctx context.Context, scopeTypeStr string,
	scopeId string, name string, clusterId string, origin string,
) (api.ImplResponse, error) {
	tenantId, apiErr := common.TenantIdFromContext(ctx)
	if apiErr != nil {
		return NewErrorResponse(apiErr), nil
	}

	if err := common.ValidateScopeType(scopeTypeStr); err != nil {
		return NewErrorResponse(err), nil
	}

	filter := &models.ObjectFilters{
		TenantId: tenantId,
		Type:     models.ObjectTypeResourceClaimTemplate,
	}
	if name != "" {
		filter.Name = &name
	}
	if clusterId != "" {
		clusterUuid, err := uuid.Parse(clusterId)
		if err != nil {
			return NewErrorResponse(api.NewError(http.StatusBadRequest, "invalid cluster ID format", nil)), nil
		}
		filter.ClusterId = clusterUuid
	}
	if scopeTypeStr != "" {
		filter.ScopeType = authclient.ScopeType(scopeTypeStr)
		// GET is intentionally more lenient than POST/PUT/DELETE: scopeId may be
		// omitted to list every row at the given scope type (e.g. all
		// project-scoped RCTs). When it is supplied, route it into the matching
		// column; the cluster-scope row already carries cluster_id and needs
		// nothing extra.
		if scopeId != "" {
			switch filter.ScopeType {
			case authclient.SCOPETYPE_DEPARTMENT:
				filter.DepartmentId = scopeId
			case authclient.SCOPETYPE_PROJECT:
				filter.ProjectId = scopeId
			}
		}
	}

	objects, apiErr := dao.ListObjects(ctx, filter)
	if apiErr != nil {
		logging.WithCtx(runaictx.LoggerHook(ctx)).Errorf("failed listing resource claim templates: %v", apiErr)
		return NewErrorResponse(apiErr), nil
	}

	result := &api.ResourceClaimTemplates{Items: make([]api.ResourceClaimTemplate, 0, len(objects))}
	for _, obj := range objects {
		rct, err := resourceClaimTemplateDbToApi(obj)
		if err != nil {
			logging.WithCtx(runaictx.LoggerHook(ctx)).Errorf("failed decoding resource claim template: %v", err)
			return NewErrorResponse(api.NewError(http.StatusInternalServerError, "failed decoding resource claim template", err)), nil
		}

		// Filter by origin at the service layer: the stored origin lives inside
		// the json spec blob, so the DB layer cannot express it as a WHERE.
		if !originMatches(origin, rct.Origin) {
			continue
		}

		result.Items = append(result.Items, *rct)
	}

	return api.Response(http.StatusOK, result), nil
}

// upsertOne drives the per-item POST/PUT path: parse the body's scope, upsert
// the single row, surface its id into HandleResourceIssues, and return the
// stored view of the record.
func (s *ResourceClaimTemplatesApiService) upsertOne(ctx context.Context, clusterId string, rct api.ResourceClaimTemplate) (api.ImplResponse, error) {
	tenantId, apiErr := common.TenantIdFromContext(ctx)
	if apiErr != nil {
		return NewErrorResponse(apiErr), nil
	}

	if rct.Name == "" {
		return NewErrorResponse(api.NewValidationError("resource claim template name is mandatory")), nil
	}
	if err := common.ValidateScopeType(string(rct.ScopeType)); err != nil {
		return NewErrorResponse(err), nil
	}

	clusterUuid, err := uuid.Parse(clusterId)
	if err != nil {
		return NewErrorResponse(api.NewError(http.StatusBadRequest, "invalid cluster ID format", nil)), nil
	}

	obj, apiErr := resourceClaimTemplateApiToDb(tenantId, clusterUuid, &rct)
	if apiErr != nil {
		return NewErrorResponse(apiErr), nil
	}

	if _, apiErr := dao.UpsertObject(ctx, obj); apiErr != nil {
		logging.WithCtx(runaictx.LoggerHook(ctx)).Errorf("failed upserting resource claim template %s: %v", rct.Name, apiErr)
		return NewErrorResponse(apiErr), nil
	}

	if _, apiErr := HandleResourceIssues(ctx, tenantId, clusterId,
		string(rct.ScopeType), rct.ScopeId, obj.ID.String(),
		rct.Issues, string(api.CLUSTERRESOURCETYPE_RESOURCE_CLAIM_TEMPLATE)); apiErr != nil {
		logging.WithCtx(runaictx.LoggerHook(ctx)).Errorf("failed updating resource issues for %s: %v", rct.Name, apiErr)
		return NewErrorResponse(apiErr), nil
	}

	stored, err := resourceClaimTemplateDbToApi(obj)
	if err != nil {
		return NewErrorResponse(api.NewError(http.StatusInternalServerError, "failed decoding resource claim template", err)), nil
	}
	return api.Response(http.StatusOK, stored), nil
}
