// ResourceClaimTemplatesApiService implements the ResourceClaimTemplatesAPIServicer
// generated by openapi-generator. ResourceClaimTemplates are tracked in the shared
// `objects` table (new ObjectType "ResourceClaimTemplate") and may live in cluster,
// department, or project scope - the scope is encoded in the URL rather than in
// the payload, so each sync call is a full-set replace within its scope.
type ResourceClaimTemplatesApiService struct{}

// NewResourceClaimTemplatesApiService creates a default api service.
func NewResourceClaimTemplatesApiService() api.ResourceClaimTemplatesAPIServicer {
	return &ResourceClaimTemplatesApiService{}
}

// SyncClusterWideResourceClaimTemplates handles the cluster-scoped sync endpoint.
func (s *ResourceClaimTemplatesApiService) SyncClusterWideResourceClaimTemplates(ctx context.Context, clusterId string, rcts api.ResourceClaimTemplates) (api.ImplResponse, error) {
	return s.syncScoped(ctx, clusterId, authclient.SCOPETYPE_CLUSTER, clusterId, rcts)
}

// SyncDepartmentWideResourceClaimTemplates handles the department-scoped sync endpoint.
func (s *ResourceClaimTemplatesApiService) SyncDepartmentWideResourceClaimTemplates(ctx context.Context, clusterId string, departmentId string, rcts api.ResourceClaimTemplates) (api.ImplResponse, error) {
	return s.syncScoped(ctx, clusterId, authclient.SCOPETYPE_DEPARTMENT, departmentId, rcts)
}

// SyncProjectResourceClaimTemplates handles the project-scoped sync endpoint. The
// scope id arrives as a namespace in the URL; we translate it to a project id so
// stored rows carry the same scope id the rest of the tracker expects.
func (s *ResourceClaimTemplatesApiService) SyncProjectResourceClaimTemplates(ctx context.Context, clusterId string, namespace string, rcts api.ResourceClaimTemplates) (api.ImplResponse, error) {
	projectId, apiErr := namespaceToProjectId(ctx, clusterId, namespace)
	if apiErr != nil {
		return NewErrorResponse(apiErr), nil
	}
	return s.syncScoped(ctx, clusterId, authclient.SCOPETYPE_PROJECT, projectId, rcts)
}

// ListResourceClaimTemplates lists tracked RCTs filtered by scope / cluster /
// name / origin. The ancestor + descendant toggles follow the same convention
// as the PVC list endpoint so callers can collapse across the scope hierarchy
// where needed.
func (s *ResourceClaimTemplatesApiService) ListResourceClaimTemplates(ctx context.Context, scopeTypeStr string,
	scopeId string, name string, clusterId string, origin string, includeAncestors bool, includeDescendants bool,
) (api.ImplResponse, error) {
	tenantId, apiErr := common.TenantIdFromContext(ctx)
	if apiErr != nil {
		return NewErrorResponse(apiErr), nil
	}

	if err := common.ValidateScopeType(scopeTypeStr); err != nil {
		return NewErrorResponse(err), nil
	}

	// Build the base filter. Cluster id is folded into the filter so a single
	// unindexed table scan is not needed to reconstruct per-cluster views.
	filter := &models.ObjectFilters{
		TenantId: tenantId,
		Type:     models.ObjectTypeResourceClaimTemplate,
	}
	if name != "" {
		filter.Name = &name
	}
	if clusterId != "" {
		clusterUuid, err := uuid.Parse(clusterId)
		if err != nil {
			return NewErrorResponse(api.NewError(http.StatusBadRequest, "invalid cluster ID format", nil)), nil
		}
		filter.ClusterId = clusterUuid
	}
	if scopeTypeStr != "" {
		filter.ScopeType = authclient.ScopeType(scopeTypeStr)
		if err := assignScopeId(filter, scopeId); err != nil {
			return NewErrorResponse(err), nil
		}
	}

	// NOTE: includeAncestors / includeDescendants are accepted for symmetry with
	// the PVC list contract but ignored for now - the objects table does not go
	// through BuildScopeQuery (which is Pvc-specific). Wiring them in is a
	// follow-up once an actual caller requires cross-scope expansion.
	_ = includeAncestors
	_ = includeDescendants

	objects, apiErr := dao.ListObjects(ctx, filter)
	if apiErr != nil {
		logging.WithCtx(runaictx.LoggerHook(ctx)).Errorf("failed listing resource claim templates: %v", apiErr)
		return NewErrorResponse(apiErr), nil
	}

	result := &api.ResourceClaimTemplates{Items: make([]api.ResourceClaimTemplate, 0, len(objects))}
	for _, obj := range objects {
		rct, err := resourceClaimTemplateDbToApi(obj)
		if err != nil {
			logging.WithCtx(runaictx.LoggerHook(ctx)).Errorf("failed decoding resource claim template: %v", err)
			return NewErrorResponse(api.NewError(http.StatusInternalServerError, "failed decoding resource claim template", err)), nil
		}

		// Filter by origin at the service layer: the stored origin lives inside
		// the json spec blob, so the DB layer cannot express it as a WHERE.
		if !originMatches(origin, rct.Origin) {
			continue
		}

		result.Items = append(result.Items, *rct)
	}

	return api.Response(http.StatusOK, result), nil
}

func (s *ResourceClaimTemplatesApiService) syncScoped(ctx context.Context, clusterId string, scopeType authclient.ScopeType, scopeId string, rcts api.ResourceClaimTemplates) (api.ImplResponse, error) {
	tenantId, apiErr := common.TenantIdFromContext(ctx)
	if apiErr != nil {
		return NewErrorResponse(apiErr), nil
	}

	clusterUuid, err := uuid.Parse(clusterId)
	if err != nil {
		return NewErrorResponse(api.NewError(http.StatusBadRequest, "invalid cluster ID format", nil)), nil
	}

	scopeFilter := &models.ObjectFilters{
		Type:      models.ObjectTypeResourceClaimTemplate,
		TenantId:  tenantId,
		ClusterId: clusterUuid,
		ScopeType: scopeType,
	}
	if err := assignScopeId(scopeFilter, scopeId); err != nil {
		return NewErrorResponse(err), nil
	}

	// Upsert each row individually (as PVC does) so we can tie the returned row
	// id back to the issues the agent reported for that template. The alternative
	// bulk UpsertObjects path does not surface the row id and is kept for the
	// DeviceClass / StorageClass flows that do not track issues.
	kept := make([]*models.Object, 0, len(rcts.Items))
	for i := range rcts.Items {
		rct := rcts.Items[i]
		if rct.Name == "" {
			return NewErrorResponse(api.NewValidationError("resource claim template name is mandatory")), nil
		}

		obj, err := resourceClaimTemplateApiToDb(scopeFilter, &rct)
		if err != nil {
			return NewErrorResponse(api.NewError(http.StatusInternalServerError, "failed marshaling resource claim template spec", err)), nil
		}

		if _, apiErr := dao.UpsertObject(ctx, obj); apiErr != nil {
			logging.WithCtx(runaictx.LoggerHook(ctx)).Errorf("failed upserting resource claim template %s: %v", rct.Name, apiErr)
			return NewErrorResponse(apiErr), nil
		}

		if _, err := HandleResourceIssues(ctx, tenantId, clusterId,
			string(scopeType), scopeId, obj.ID.String(),
			rct.Issues, string(api.CLUSTERRESOURCETYPE_RESOURCE_CLAIM_TEMPLATE)); err != nil {
			logging.WithCtx(runaictx.LoggerHook(ctx)).Errorf("failed updating resource issues for %s: %v", rct.Name, err)
			return NewErrorResponse(err), nil
		}

		kept = append(kept, obj)
	}

	// Prune within this (cluster, scopeType, scopeId) window: anything we did
	// not see in this payload no longer exists on the cluster.
	if apiErr := dao.DeleteObjectsNotInCluster(ctx, scopeFilter, kept); apiErr != nil {
		logging.WithCtx(runaictx.LoggerHook(ctx)).Errorf("failed pruning stale resource claim templates: %v", apiErr)
		return NewErrorResponse(apiErr), nil
	}

	return api.Response(http.StatusOK, rcts), nil
}
