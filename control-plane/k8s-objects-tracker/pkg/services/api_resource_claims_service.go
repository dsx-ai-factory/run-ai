// ResourceClaimsApiService implements the ResourceClaimsAPIServicer generated by
// openapi-generator. ResourceClaims are always project-scoped (per Run.ai asset
// model, claims are never originated from assets, only templates are), so the
// sync surface is a single endpoint and the stored origin is implicitly
// "existing".
type ResourceClaimsApiService struct{}

// NewResourceClaimsApiService creates a default api service.
func NewResourceClaimsApiService() api.ResourceClaimsAPIServicer {
	return &ResourceClaimsApiService{}
}

// SyncProjectResourceClaims replaces the known-claim set within the given
// (cluster, namespace). The namespace is translated to a project id before
// anything is persisted so stored rows carry the same scope id convention as
// the rest of the tracker.
func (s *ResourceClaimsApiService) SyncProjectResourceClaims(ctx context.Context, clusterId string, namespace string, rcs api.ResourceClaims) (api.ImplResponse, error) {
	tenantId, apiErr := common.TenantIdFromContext(ctx)
	if apiErr != nil {
		return NewErrorResponse(apiErr), nil
	}

	clusterUuid, err := uuid.Parse(clusterId)
	if err != nil {
		return NewErrorResponse(api.NewError(http.StatusBadRequest, "invalid cluster ID format", nil)), nil
	}

	projectId, apiErr := namespaceToProjectId(ctx, clusterId, namespace)
	if apiErr != nil {
		return NewErrorResponse(apiErr), nil
	}

	scopeFilter := &models.ObjectFilters{
		Type:      models.ObjectTypeResourceClaim,
		TenantId:  tenantId,
		ClusterId: clusterUuid,
		ScopeType: authclient.SCOPETYPE_PROJECT,
		ProjectId: projectId,
	}

	kept := make([]*models.Object, 0, len(rcs.Items))
	for i := range rcs.Items {
		rc := rcs.Items[i]
		if rc.Name == "" {
			return NewErrorResponse(api.NewValidationError("resource claim name is mandatory")), nil
		}

		obj, err := resourceClaimApiToDb(scopeFilter, &rc)
		if err != nil {
			return NewErrorResponse(api.NewError(http.StatusInternalServerError, "failed marshaling resource claim spec", err)), nil
		}

		if _, apiErr := dao.UpsertObject(ctx, obj); apiErr != nil {
			logging.WithCtx(runaictx.LoggerHook(ctx)).Errorf("failed upserting resource claim %s: %v", rc.Name, apiErr)
			return NewErrorResponse(apiErr), nil
		}

		if _, err := HandleResourceIssues(ctx, tenantId, clusterId,
			string(authclient.SCOPETYPE_PROJECT), projectId, obj.ID.String(),
			rc.Issues, string(api.CLUSTERRESOURCETYPE_RESOURCE_CLAIM)); err != nil {
			logging.WithCtx(runaictx.LoggerHook(ctx)).Errorf("failed updating resource issues for %s: %v", rc.Name, err)
			return NewErrorResponse(err), nil
		}

		kept = append(kept, obj)
	}

	if apiErr := dao.DeleteObjectsNotInCluster(ctx, scopeFilter, kept); apiErr != nil {
		logging.WithCtx(runaictx.LoggerHook(ctx)).Errorf("failed pruning stale resource claims: %v", apiErr)
		return NewErrorResponse(apiErr), nil
	}

	return api.Response(http.StatusOK, rcs), nil
}

// ListResourceClaims lists tracked ResourceClaims. Only project scope is
// meaningful here (claims never live in cluster / department scopes), but we
// still accept the common filter set for symmetry with the PVC / RCT lists.
func (s *ResourceClaimsApiService) ListResourceClaims(ctx context.Context, scopeTypeStr string, scopeId string, name string, clusterId string, includeAncestors bool, includeDescendants bool) (api.ImplResponse, error) {
	tenantId, apiErr := common.TenantIdFromContext(ctx)
	if apiErr != nil {
		return NewErrorResponse(apiErr), nil
	}

	if err := common.ValidateScopeType(scopeTypeStr); err != nil {
		return NewErrorResponse(err), nil
	}

	filter := &models.ObjectFilters{
		TenantId: tenantId,
		Type:     models.ObjectTypeResourceClaim,
	}
	if name != "" {
		filter.Name = &name
	}
	if clusterId != "" {
		clusterUuid, err := uuid.Parse(clusterId)
		if err != nil {
			return NewErrorResponse(api.NewError(http.StatusBadRequest, "invalid cluster ID format", nil)), nil
		}
		filter.ClusterId = clusterUuid
	}
	if scopeTypeStr != "" {
		filter.ScopeType = authclient.ScopeType(scopeTypeStr)
		if err := assignScopeId(filter, scopeId); err != nil {
			return NewErrorResponse(err), nil
		}
	}

	_ = includeAncestors
	_ = includeDescendants

	objects, apiErr := dao.ListObjects(ctx, filter)
	if apiErr != nil {
		logging.WithCtx(runaictx.LoggerHook(ctx)).Errorf("failed listing resource claims: %v", apiErr)
		return NewErrorResponse(apiErr), nil
	}

	result := &api.ResourceClaims{Items: make([]api.ResourceClaim, 0, len(objects))}
	for _, obj := range objects {
		rc, err := resourceClaimDbToApi(obj)
		if err != nil {
			logging.WithCtx(runaictx.LoggerHook(ctx)).Errorf("failed decoding resource claim: %v", err)
			return NewErrorResponse(api.NewError(http.StatusInternalServerError, "failed decoding resource claim", err)), nil
		}
		result.Items = append(result.Items, *rc)
	}

	return api.Response(http.StatusOK, result), nil
}

// resourceClaimSpecEnvelope is the shape persisted inside the objects row's
// `spec` jsonb column for a ResourceClaim. Mirrors the RCT envelope: the
// non-identifying fields that have no column of their own go here.
type resourceClaimSpecEnvelope struct {
	Namespace                 string                 `json:"namespace,omitempty"`
	ResourceClaimTemplateName *string                `json:"resourceClaimTemplateName,omitempty"`
	Spec                      map[string]interface{} `json:"spec,omitempty"`
}

func resourceClaimApiToDb(scopeFilter *models.ObjectFilters, rc *api.ResourceClaim) (*models.Object, error) {
	envelope := resourceClaimSpecEnvelope{
		Namespace:                 rc.Namespace,
		ResourceClaimTemplateName: rc.ResourceClaimTemplateName,
		Spec:                      rc.Spec,
	}
	buf, err := json.Marshal(envelope)
	if err != nil {
		return nil, err
	}

	filters := *scopeFilter
	filters.Name = ptr.To(rc.Name)

	return &models.Object{
		ObjectFilters: filters,
		Spec:          string(buf),
	}, nil
}

func resourceClaimDbToApi(obj *models.Object) (*api.ResourceClaim, error) {
	envelope := resourceClaimSpecEnvelope{}
	if obj.Spec != "" {
		if err := json.Unmarshal([]byte(obj.Spec), &envelope); err != nil {
			return nil, err
		}
	}

	name := ""
	if obj.Name != nil {
		name = *obj.Name
	}

	return &api.ResourceClaim{
		Name:                      name,
		Namespace:                 envelope.Namespace,
		ResourceClaimTemplateName: envelope.ResourceClaimTemplateName,
		Spec:                      envelope.Spec,
	}, nil
}
