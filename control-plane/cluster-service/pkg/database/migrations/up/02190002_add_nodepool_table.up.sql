CREATE TABLE IF NOT EXISTS nodepools
(
    id             BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (START WITH 10000),
    name           TEXT NOT NULL,
    tenant_id      INT,
    label_key      TEXT,
    label_value    TEXT,
    phase          TEXT NOT NULL,
    phase_message  TEXT,
    cluster_id     UUID NOT NULL,
    cluster_name   TEXT NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL,
    updated_at     TIMESTAMPTZ NOT NULL,
    deleted_at     TIMESTAMPTZ,
    created_by     TEXT NOT NULL,
    updated_by     TEXT NOT NULL,
    deleted_by     TEXT,
    is_default     BOOLEAN NOT NULL DEFAULT FALSE,
    over_provisioning_ratio integer NOT NULL DEFAULT 1,
    gpu_placement_strategy TEXT NOT NULL DEFAULT 'binpack',
    cpu_placement_strategy TEXT NOT NULL DEFAULT 'binpack',

    CONSTRAINT np_unique_cluster_name UNIQUE (cluster_id, name, deleted_at),
    CONSTRAINT np_cluster_id_fk FOREIGN KEY (cluster_id) REFERENCES clusters (id) ON DELETE CASCADE
);

CREATE UNIQUE INDEX IF NOT EXISTS np_unique_key_value ON nodepools (cluster_id, label_key, label_value) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_np_tenant_cluster ON nodepools (tenant_id, cluster_id);
CREATE INDEX IF NOT EXISTS idx_np_name ON nodepools (name);
CREATE INDEX IF NOT EXISTS idx_np_phase ON nodepools (phase);
CREATE INDEX IF NOT EXISTS idx_np_created_at ON nodepools (created_at);
