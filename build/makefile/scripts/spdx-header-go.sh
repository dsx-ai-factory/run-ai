# Inject the NVIDIA SPDX header into generated Go mock files (idempotent).
#
# mockery and mockgen (GoMock) emit no license header, so mocks are generated
# header-less. The mock-generation make targets (`generate-mocks` /
# `generate-mocks-client` for mockery; `generate-mockgen` for GoMock) run this
# immediately after the generator, so every regenerated mock carries the header
# (do not hand-stamp — regen would wipe it). Also usable standalone to backfill:
#
#   sh build/makefile/scripts/spdx-header-go.sh <dir>   # default <dir> = .
#
# Scope: only files under a `mocks/` directory that carry a generated-mock
# marker ("Code generated by mockery" or "Code generated by MockGen") are
# touched — hand-written and third-party code is left alone. Already-headered
# files are skipped (idempotent).
set -eu

H1='// SPDX-FileCopyrightText: Copyright (c) 2026 NVIDIA CORPORATION & AFFILIATES. All rights reserved.'
H2='// SPDX-License-Identifier: Apache-2.0'

root="${1:-.}"

find "$root" -type f \( -path '*/mocks/*.go' -o -path '*/mock/*.go' -o -name '*_mock.go' \) 2>/dev/null | while IFS= read -r f; do
	# Only generated mocks; skip anything already headered.
	head -n 2 "$f" | grep -qE 'Code generated by (mockery|MockGen)' || continue
	head -n 3 "$f" | grep -q 'SPDX-FileCopyrightText' && continue
	tmp="${f}.spdxtmp.$$"
	# Preserve any leading Go build-constraint lines; insert the header above the
	# generated banner otherwise.
	awk -v h1="$H1" -v h2="$H2" '
		BEGIN { done = 0 }
		NR <= 2 && ($0 ~ /^\/\/go:build/ || $0 ~ /^\/\/ \+build/) { print; next }
		!done { print h1; print h2; print ""; done = 1 }
		{ print }
	' "$f" > "$tmp" && mv "$tmp" "$f"
done
