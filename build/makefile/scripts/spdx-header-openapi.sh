# Inject the NVIDIA SPDX header into openapi-generator Go client files (idempotent).
# openapi-generator's default Go templates emit no license header. Generate targets
# run this after generation so regen reproduces the header (do not hand-stamp alone).
# Header goes at the very top, above the generator's /* <AppName> ... */ banner,
# matching the already-headered clients (runai-clients/cli-exposer-client/generated).
#   sh spdx-header-openapi.sh <dir>   # default <dir> = .
set -eu
H1='// SPDX-FileCopyrightText: Copyright (c) 2026 NVIDIA CORPORATION & AFFILIATES. All rights reserved.'
H2='// SPDX-License-Identifier: Apache-2.0'
root="${1:-.}"
find "$root" -type f -name '*.go' 2>/dev/null | grep -vE '/vendor/|/third_party/|/thirdpartyapi/' | while IFS= read -r f; do
	head -n 15 "$f" | grep -q 'Code generated by OpenAPI Generator' || continue
	head -n 3 "$f" | grep -q 'SPDX-FileCopyrightText' && continue
	tmp="${f}.spdxtmp.$$"
	{ printf '%s\n%s\n' "$H1" "$H2"; cat "$f"; } > "$tmp" && mv "$tmp" "$f"
done
