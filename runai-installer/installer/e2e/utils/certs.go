package utils

import (
	"fmt"
	"os"
	"path/filepath"
)

const (
	DefaultTestDomain         = "test.runai.local"
	DefaultTestWildcardDomain = "*.inference.test.runai.local"
)

var (
	TestDomain         string
	TestWildcardDomain string
)

func init() {
	TestDomain = os.Getenv("E2E_TEST_DOMAIN")
	if TestDomain == "" {
		TestDomain = DefaultTestDomain
	}

	TestWildcardDomain = os.Getenv("E2E_TEST_WILDCARD_DOMAIN")
	if TestWildcardDomain == "" {
		TestWildcardDomain = DefaultTestWildcardDomain
	}
}

var requiredSecretFiles = []string{
	"runai_pull_secret",
}

// optionalSecretFiles are copied from the source secrets dir if present. TLS
// material is generated by SetupTestEnv itself, so workflows are no longer
// required to ship cert/key files.
var optionalSecretFiles = []string{
	"tls.crt",
	"tls.key",
	"ca.crt",
	"wildcard.crt",
	"wildcard.key",
}

func CopySecretsFromDir(srcDir, destDir string) error {
	for _, filename := range requiredSecretFiles {
		srcPath := filepath.Join(srcDir, filename)
		destPath := filepath.Join(destDir, filename)

		if err := CopyFile(srcPath, destPath); err != nil {
			return fmt.Errorf("failed to copy %s: %w", filename, err)
		}
	}

	for _, filename := range optionalSecretFiles {
		srcPath := filepath.Join(srcDir, filename)
		destPath := filepath.Join(destDir, filename)

		if err := CopyFile(srcPath, destPath); err == nil {
			fmt.Printf("Copied optional file: %s\n", filename)
		}
	}

	return nil
}
