package utils

import (
	"bytes"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"runtime"

	_ "github.com/onsi/ginkgo/v2"
	shared "github.com/run-ai/runai/runai-installer/installer/e2e/utils"
)

type DockerComposeEnv struct {
	WorkDir    string
	SecretsDir string
	CertSet    *shared.CertificateSet
}

func getDockerComposeSourceDir() string {
	_, currentFile, _, _ := runtime.Caller(0)
	return filepath.Join(filepath.Dir(currentFile), "..", "..", "poller_docker_compose")
}

// patchProvisionerImage replaces the provisioner image if E2E_COMPOSE_PROVISIONER_IMAGE is set.
func (e *DockerComposeEnv) patchProvisionerImage() error {
	customImage := os.Getenv("E2E_COMPOSE_PROVISIONER_IMAGE")
	if customImage == "" {
		return nil
	}

	composePath := filepath.Join(e.WorkDir, "docker-compose.yml")
	content, err := os.ReadFile(composePath)
	if err != nil {
		return fmt.Errorf("failed to read docker-compose.yml: %w", err)
	}

	re := regexp.MustCompile(`image:\s*nvcr\.io/nvidia/runai/runai-provisioner:[^\s]+`)
	newContent := re.ReplaceAll(content, []byte(fmt.Sprintf("image: %s", customImage)))

	if err := os.WriteFile(composePath, newContent, 0644); err != nil {
		return fmt.Errorf("failed to write docker-compose.yml: %w", err)
	}

	fmt.Printf("Patched provisioner image to: %s\n", customImage)
	return nil
}

// SetupDockerComposeEnv creates a clean temp directory with docker-compose files and secrets.
func SetupDockerComposeEnv(secretsSourceDir string) (*DockerComposeEnv, error) {
	workDir, err := os.MkdirTemp("", "provisioner-docker-compose-e2e-*")
	if err != nil {
		return nil, fmt.Errorf("failed to create temp dir: %w", err)
	}

	env := &DockerComposeEnv{
		WorkDir:    workDir,
		SecretsDir: filepath.Join(workDir, "runai-secrets"),
	}

	if err := os.MkdirAll(env.SecretsDir, 0755); err != nil {
		os.RemoveAll(workDir)
		return nil, fmt.Errorf("failed to create secrets dir: %w", err)
	}

	sourceDir := getDockerComposeSourceDir()
	filesToCopy := []string{"docker-compose.yml", "poll.py"}
	for _, file := range filesToCopy {
		if err := shared.CopyFile(filepath.Join(sourceDir, file), filepath.Join(workDir, file)); err != nil {
			os.RemoveAll(workDir)
			return nil, fmt.Errorf("failed to copy %s: %w", file, err)
		}
	}

	if err := env.patchProvisionerImage(); err != nil {
		os.RemoveAll(workDir)
		return nil, fmt.Errorf("failed to patch provisioner image: %w", err)
	}

	if err := env.copySecrets(secretsSourceDir); err != nil {
		os.RemoveAll(workDir)
		return nil, fmt.Errorf("failed to copy secrets: %w", err)
	}

	if err := env.EnableSelfSignedCA(); err != nil {
		os.RemoveAll(workDir)
		return nil, fmt.Errorf("failed to generate self-signed certs: %w", err)
	}

	kubeconfig := os.Getenv("KUBECONFIG")
	if kubeconfig == "" {
		kubeconfig = filepath.Join(os.Getenv("HOME"), ".kube", "config")
	}
	if err := shared.CopyFile(kubeconfig, filepath.Join(env.SecretsDir, "kubeconfig")); err != nil {
		os.RemoveAll(workDir)
		return nil, fmt.Errorf("failed to copy kubeconfig: %w", err)
	}

	if err := env.makeSecretsReadable(); err != nil {
		os.RemoveAll(workDir)
		return nil, fmt.Errorf("failed to make secrets readable: %w", err)
	}

	return env, nil
}

func (e *DockerComposeEnv) copySecrets(secretsSourceDir string) error {
	// runai_jfrog_token is the only required artifact from the source secrets
	// dir; TLS material is generated by EnableSelfSignedCA below.
	required := []string{"runai_jfrog_token"}
	for _, name := range required {
		srcPath := filepath.Join(secretsSourceDir, name)
		destPath := filepath.Join(e.SecretsDir, name)
		if err := shared.CopyFile(srcPath, destPath); err != nil {
			return fmt.Errorf("failed to copy %s: %w", name, err)
		}
	}

	return nil
}

// makeSecretsReadable sets file permissions so the container's nonroot user can read them.
func (e *DockerComposeEnv) makeSecretsReadable() error {
	entries, err := os.ReadDir(e.SecretsDir)
	if err != nil {
		return fmt.Errorf("failed to read secrets dir: %w", err)
	}

	for _, entry := range entries {
		if !entry.IsDir() {
			path := filepath.Join(e.SecretsDir, entry.Name())
			if err := os.Chmod(path, 0644); err != nil {
				return fmt.Errorf("failed to chmod %s: %w", entry.Name(), err)
			}
		}
	}
	return nil
}

// EnableSelfSignedCA generates self-signed certificates and configures the environment to use them.
func (e *DockerComposeEnv) EnableSelfSignedCA() error {
	certSet, err := shared.GenerateSelfSignedCerts(TestDomain, TestWildcardDomain)
	if err != nil {
		return fmt.Errorf("failed to generate self-signed certs: %w", err)
	}
	e.CertSet = certSet

	if err := shared.CopyFile(certSet.ServerCertPath, filepath.Join(e.SecretsDir, "tls.crt")); err != nil {
		return fmt.Errorf("failed to copy server cert: %w", err)
	}
	if err := shared.CopyFile(certSet.ServerKeyPath, filepath.Join(e.SecretsDir, "tls.key")); err != nil {
		return fmt.Errorf("failed to copy server key: %w", err)
	}
	if err := shared.CopyFile(certSet.CACertPath, filepath.Join(e.SecretsDir, "ca.crt")); err != nil {
		return fmt.Errorf("failed to copy CA cert: %w", err)
	}
	if err := shared.CopyFile(certSet.ServerCertPath, filepath.Join(e.SecretsDir, "wildcard.crt")); err != nil {
		return fmt.Errorf("failed to copy wildcard cert: %w", err)
	}
	if err := shared.CopyFile(certSet.ServerKeyPath, filepath.Join(e.SecretsDir, "wildcard.key")); err != nil {
		return fmt.Errorf("failed to copy wildcard key: %w", err)
	}

	if err := e.makeSecretsReadable(); err != nil {
		return fmt.Errorf("failed to make secrets readable: %w", err)
	}

	return nil
}

func (e *DockerComposeEnv) GetCAChainPath() string {
	if TestK8sDistribution == "openshift" {
		return ""
	}
	if e.CertSet != nil {
		return filepath.Join(e.SecretsDir, "ca.crt")
	}
	return ""
}

// RunDockerCompose runs docker-compose and returns the poller's exit code.
// Logs are streamed to GinkgoWriter in real-time and also returned.
func (e *DockerComposeEnv) RunDockerCompose(provisioningMode, userEmail string) (int, string, error) {
	envVars := []string{
		fmt.Sprintf("DOMAIN=%s", TestDomain),
		fmt.Sprintf("WILDCARD_DOMAIN=%s", TestWildcardDomain),
		fmt.Sprintf("PROVISIONING_MODE=%s", provisioningMode),
		fmt.Sprintf("USER_EMAIL=%s", userEmail),
		fmt.Sprintf("TLS_CERT_PATH=%s", filepath.Join(e.SecretsDir, "tls.crt")),
		fmt.Sprintf("TLS_KEY_PATH=%s", filepath.Join(e.SecretsDir, "tls.key")),
		fmt.Sprintf("WILDCARD_CERT_PATH=%s", filepath.Join(e.SecretsDir, "wildcard.crt")),
		fmt.Sprintf("WILDCARD_KEY_PATH=%s", filepath.Join(e.SecretsDir, "wildcard.key")),
		fmt.Sprintf("SECRETS_PATH=%s", e.SecretsDir),
		fmt.Sprintf("KUBECONFIG=%s", filepath.Join(e.SecretsDir, "kubeconfig")),
	}

	if caPath := e.GetCAChainPath(); caPath != "" {
		envVars = append(envVars, fmt.Sprintf("CA_CHAIN_PATH=%s", caPath))
	}

	if TestK8sDistribution != "" && TestK8sDistribution != "kind" {
		envVars = append(envVars, fmt.Sprintf("KUBERNETES_DISTRIBUTION=%s", TestK8sDistribution))
	}

	cmd := exec.Command("docker", "compose", "up", "--abort-on-container-exit", "--exit-code-from", "poller")
	cmd.Dir = e.WorkDir
	cmd.Env = append(os.Environ(), envVars...)

	// Stream logs to stdout in real-time while also capturing them
	var outputBuf bytes.Buffer
	multiWriter := io.MultiWriter(&outputBuf, os.Stdout)
	cmd.Stdout = multiWriter
	cmd.Stderr = multiWriter

	err := cmd.Run()
	exitCode := 0
	if err != nil {
		if exitErr, ok := err.(*exec.ExitError); ok {
			exitCode = exitErr.ExitCode()
		} else {
			return -1, outputBuf.String(), fmt.Errorf("failed to run docker-compose: %w", err)
		}
	}

	return exitCode, outputBuf.String(), nil
}

// Cleanup stops docker-compose and removes the temp directory.
func (e *DockerComposeEnv) Cleanup() error {
	cmd := exec.Command("docker", "compose", "down", "-v", "--remove-orphans")
	cmd.Dir = e.WorkDir
	_ = cmd.Run()

	if e.CertSet != nil {
		_ = e.CertSet.Cleanup()
	}

	if e.WorkDir != "" {
		return os.RemoveAll(e.WorkDir)
	}
	return nil
}
