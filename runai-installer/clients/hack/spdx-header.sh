# Inject the NVIDIA SPDX header into openapi-generator Go client files (idempotent).
#
# openapi-generator's default Go templates emit no license header, so generated
# clients are header-less. The `generate` make target runs this immediately after
# generation, so every regenerated client carries the header (do not hand-stamp
# alone — regen would wipe it). Header goes at the very top, above the generator's
# `/* <AppName> ... */` banner — matching the already-headered clients elsewhere
# in the repo (e.g. runai-clients/cli-exposer-client/generated).
#
#   sh hack/spdx-header.sh <dir>   # default <dir> = .
#
# Scope: only files carrying the "Code generated by OpenAPI Generator" marker are
# touched; already-headered files are skipped.
set -eu

H1='// SPDX-FileCopyrightText: Copyright (c) 2026 NVIDIA CORPORATION & AFFILIATES. All rights reserved.'
H2='// SPDX-License-Identifier: Apache-2.0'

root="${1:-.}"

# Remove unused generator scaffolding. git_push.sh is emitted by
# openapi-generator but never used; deleting it on every generation keeps it out
# of the tree rather than leaving an unheadered file behind.
find "$root" -type f -name 'git_push.sh' 2>/dev/null | while IFS= read -r f; do
	rm -f "$f"
done

find "$root" -type f -name '*.go' 2>/dev/null | while IFS= read -r f; do
	# Only openapi-generated files; skip anything already headered.
	head -n 15 "$f" | grep -q 'Code generated by OpenAPI Generator' || continue
	head -n 3 "$f" | grep -q 'SPDX-FileCopyrightText' && continue
	tmp="${f}.spdxtmp.$$"
	{ printf '%s\n%s\n' "$H1" "$H2"; cat "$f"; } > "$tmp" && mv "$tmp" "$f"
done
